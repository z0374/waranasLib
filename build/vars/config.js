#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/*
 * ============================================================
 * WARANAS BUILD
 * ============================================================
 *
 * Estrutura esperada da biblioteca:
 *
 * waranas/
 * ├── public/
 * │   ├── config.ts
 * │   └── main.index.ts
 * │
 * └── private/
 *     └── private.index.ts
 *
 * O build é executado sobre o projeto consumidor.
 *
 * O projeto consumidor possui:
 *
 * projeto/
 * ├── *.config
 * ├── src/
 * └── node_modules/
 *     └── waranas/
 *
 * Durante o build:
 *
 * projeto/node_modules/waranas/private/
 * ├── private.index.ts
 * └── config.generated.ts
 *
 * ============================================================
 */

/*
 * Diretório do projeto consumidor.
 *
 * O build deve ser executado na raiz da aplicação.
 */
const projectRoot = process.cwd();

/*
 * Localização da instalação da Waranas.
 *
 * Como este script pertence à própria biblioteca,
 * __dirname aponta para algo como:
 *
 * node_modules/waranas/build
 */
const waranasRoot = path.resolve(__dirname, "..");

/*
 * Estrutura pública e privada da Waranas.
 */
const publicDir = path.join(waranasRoot, "public");

const privateDir = path.join(waranasRoot, "private");

/*
 * Arquivos centrais.
 */
const mainIndex = path.join(publicDir, "main.index.ts");

const privateIndex = path.join(privateDir, "private.index.ts");

/*
 * Arquivo gerado pela configuração da aplicação.
 */
const generatedConfig = path.join(privateDir, "config.generated.ts");

/*
 * ============================================================
 * UTILIDADES
 * ============================================================
 */

function fail(message) {
  console.error(`\n✗ ${message}\n`);
  process.exit(1);
}

function findConfig() {
  const files = fs.readdirSync(projectRoot);

  const configs = files.filter((file) => file.endsWith(".config"));

  if (configs.length === 0) {
    fail("Nenhum arquivo .config foi encontrado.");
  }

  if (configs.length > 1) {
    fail(
      "Mais de um arquivo .config foi encontrado:\n\n" +
        configs.map((file) => `  ${file}`).join("\n"),
    );
  }

  return path.join(projectRoot, configs[0]);
}

/*
 * ============================================================
 * PARSER DO .CONFIG
 * ============================================================
 *
 * Formato:
 *
 * entry_point=/api
 * default_lang=pt-BR
 * asset_url=https://assets.example.com
 *
 * Comentários:
 *
 * # comentário
 */
function parseConfig(file) {
  const content = fs.readFileSync(file, "utf8");

  const config = {};

  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();

    /*
     * Ignora linhas vazias.
     */
    if (!line) {
      continue;
    }

    /*
     * Ignora comentários.
     */
    if (line.startsWith("#")) {
      continue;
    }

    /*
     * Procura o primeiro "=".
     */
    const separator = line.indexOf("=");

    if (separator === -1) {
      continue;
    }

    const key = line.slice(0, separator).trim();

    const value = line.slice(separator + 1).trim();

    if (!key) {
      continue;
    }

    config[key] = value;
  }

  return config;
}

/*
 * ============================================================
 * GERA CONFIG.GENERATED.TS
 * ============================================================
 */

function generateConfig(config) {
  const lines = [
    "// ============================================================",
    "// AUTO-GENERATED BY WARANAS BUILD",
    "// DO NOT EDIT",
    "// ============================================================",
    "",
    'import { config } from "../public/config";',
    "",
  ];

  for (const [key, value] of Object.entries(config)) {
    lines.push(`config[${JSON.stringify(key)}] = ${JSON.stringify(value)};`);
  }

  lines.push("");

  return lines.join("\n");
}

/*
 * ============================================================
 * APPEND NO PRIVATE.INDEX.TS
 * ============================================================
 *
 * Regra:
 *
 * - nunca apagar conteúdo;
 * - nunca modificar exports existentes;
 * - nunca reorganizar;
 * - apenas adicionar no final;
 * - não adicionar duas vezes o mesmo export.
 */
function appendPrivateExport(moduleName) {
  const statement = `export * from "./${moduleName}";`;

  let content = "";

  if (fs.existsSync(privateIndex)) {
    content = fs.readFileSync(privateIndex, "utf8");
  }

  /*
   * Evita duplicação.
   */
  const lines = content.split(/\r?\n/).map((line) => line.trim());

  if (lines.includes(statement)) {
    console.log(`✓ Export já registrado: ${statement}`);

    return;
  }

  /*
   * Garante que o append comece em uma nova linha.
   */
  if (content.length > 0 && !content.endsWith("\n")) {
    content += "\n";
  }

  content += `${statement}\n`;

  fs.writeFileSync(privateIndex, content, "utf8");

  console.log(`✓ Export adicionado: ${statement}`);
}

/*
 * ============================================================
 * PREPARAÇÃO
 * ============================================================
 */

function prepareDirectories() {
  /*
   * O private precisa existir.
   */
  fs.mkdirSync(privateDir, {
    recursive: true,
  });

  /*
   * O índice privado é permanente.
   *
   * Se ainda não existir, criamos.
   */
  if (!fs.existsSync(privateIndex)) {
    fs.writeFileSync(
      privateIndex,
      [
        "// ============================================================",
        "// WARANAS PRIVATE BUILD INDEX",
        "// ============================================================",
        "",
      ].join("\n"),
      "utf8",
    );
  }
}

/*
 * ============================================================
 * BUNDLE
 * ============================================================
 *
 * Aqui usamos o main.index.ts da própria Waranas
 * como entry point.
 *
 * O main.index.ts importa:
 *
 * export * from "../private/private.index";
 *
 * Portanto o grafo será:
 *
 * main.index
 *     ↓
 * private.index
 *     ↓
 * config.generated
 *     ↓
 * config
 */
function bundle() {
  console.log("\n▶ Bundling Waranas...\n");

  const result = spawnSync(
    "npx",
    [
      "esbuild",

      mainIndex,

      "--bundle",

      "--format=esm",

      "--outfile=" + path.join(projectRoot, "dist", "index.js"),
    ],
    {
      cwd: projectRoot,
      stdio: "inherit",
      shell: true,
    },
  );

  if (result.error) {
    fail(`Falha ao executar o bundler:\n${result.error.message}`);
  }

  if (result.status !== 0) {
    fail("O bundler terminou com erro.");
  }

  console.log("\n✓ Bundle concluído.");
}

/*
 * ============================================================
 * BUILD
 * ============================================================
 */

function build() {
  console.log("\n========================================");

  console.log("        WARANAS BUILD");

  console.log("========================================\n");

  /*
   * 1. Localiza configuração.
   */
  const configFile = findConfig();

  console.log(`✓ Config encontrado: ${path.relative(projectRoot, configFile)}`);

  /*
   * 2. Prepara /private.
   */
  prepareDirectories();

  /*
   * 3. Lê .config.
   */
  const config = parseConfig(configFile);

  /*
   * 4. Gera config.generated.ts.
   */
  const generated = generateConfig(config);

  fs.writeFileSync(generatedConfig, generated, "utf8");

  console.log(
    `✓ Config gerado: ${path.relative(projectRoot, generatedConfig)}`,
  );

  /*
   * 5. Registra o módulo no índice privado.
   */
  appendPrivateExport("config.generated");

  /*
   * 6. Executa o bundler.
   */
  bundle();

  console.log("\n========================================");

  console.log("        WARANAS BUILD OK");

  console.log("========================================\n");
}

build();
